#!/usr/bin/env python3
"""Generate the task and environment catalog pages from the corpus itself.

Hand-maintained inventory pages go stale the moment someone adds a task, and a
stale inventory is worse than none — it is what a reader checks first and what an
answer engine quotes. These two pages are therefore derived, never edited:

    python scripts/gen_catalog.py            # write the pages
    python scripts/gen_catalog.py --check    # fail if they are out of date (CI)

Outputs:
    docs/reference/task-catalog.md
    docs/reference/environment-catalog.md
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
TASK_PAGE = ROOT / "docs" / "reference" / "task-catalog.md"
ENV_PAGE = ROOT / "docs" / "reference" / "environment-catalog.md"

GENERATED_NOTE = (
    "<!-- Generated by scripts/gen_catalog.py — do not edit by hand. "
    "Run `make catalog` after changing the corpus. -->"
)

QCAT_DESCRIPTIONS = {
    "JOB": "Job submission, scheduling, and queue reasoning",
    "MON": "Monitoring and telemetry interpretation",
    "ENERGY": "Power and energy reasoning",
    "PERF": "Performance analysis and bottleneck attribution",
    "DATA": "Data movement, storage, and filesystem operations",
    "SEC": "Security posture and access questions",
    "FAC": "Facility and cooling operations",
    "ARCH": "Architecture and capability questions",
    "AIOPS": "Anomaly detection and incident response",
    "DOCS": "Documentation lookup and policy grounding",
}


def _load_tasks() -> list[dict[str, Any]]:
    spec_dir = ROOT / "benchmark" / "tasks" / "specs"
    return [json.loads(p.read_text(encoding="utf-8")) for p in sorted(spec_dir.glob("*.json"))]


def _load_envs() -> list[dict[str, Any]]:
    env_root = ROOT / "benchmark" / "environments"
    envs = []
    for path in sorted(p for p in env_root.iterdir() if p.is_dir() and p.name.startswith("env_")):
        meta: dict[str, Any] = {"environment_id": path.name}
        meta_path = path / "metadata.yaml"
        if meta_path.is_file():
            loaded = yaml.safe_load(meta_path.read_text(encoding="utf-8")) or {}
            if isinstance(loaded, dict):
                meta.update(loaded)
        envs.append(meta)
    return envs


def _escape(text: Any) -> str:
    """Make a value safe to drop into a Markdown table cell."""
    return str(text or "").replace("|", "\\|").replace("\n", " ").strip()


def render_task_catalog(tasks: list[dict[str, Any]]) -> str:
    by_qcat: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for task in tasks:
        by_qcat[str(task.get("qcat", "UNKNOWN"))].append(task)

    roles = Counter(str(t.get("role", "")) for t in tasks)
    splits = Counter(str(t.get("benchmark_split", "")) for t in tasks)
    grounded = sum(1 for t in tasks if str(t.get("task_id", "")).startswith("M100_"))

    lines = [
        "---",
        'title: "AOBench task catalog — every HPC agent task in the benchmark"',
        (
            'description: "The complete catalog of AOBench\'s '
            f'{len(tasks)} HPC operational tasks, grouped by question category, '
            'with role, benchmark split, target environment, and difficulty for each."'
        ),
        "---",
        "",
        GENERATED_NOTE,
        "",
        "# Task catalog",
        "",
        (
            f"AOBench contains **{len(tasks)} tasks** across "
            f"**{len(by_qcat)} question categories (QCATs)** and "
            f"**{len(roles)} operator roles**. "
            f"**{grounded}** of them are grounded in real Marconi100 ExaData rather than "
            "synthesised."
        ),
        "",
        (
            f"Splits: **{splits.get('dev', 0)} dev** (open) and "
            f"**{splits.get('test', 0)} test** (held out behind `AOBENCH_UNLOCK_TEST=1`)."
        ),
        "",
        "Reproduce this page from your own checkout:",
        "",
        "```bash",
        "aobench list tasks --json",
        "```",
        "",
        "## Coverage at a glance",
        "",
        "| QCAT | Tasks | What it probes |",
        "|---|---:|---|",
    ]
    for qcat in sorted(by_qcat):
        lines.append(
            f"| [`{qcat}`](#{qcat.lower()}) | {len(by_qcat[qcat])} | "
            f"{QCAT_DESCRIPTIONS.get(qcat, '')} |"
        )

    lines += ["", "| Role | Tasks |", "|---|---:|"]
    for role, count in sorted(roles.items()):
        lines.append(f"| `{role}` | {count} |")

    for qcat in sorted(by_qcat):
        lines += [
            "",
            f"## {qcat}",
            "",
            QCAT_DESCRIPTIONS.get(qcat, ""),
            "",
            "| Task ID | Role | Split | Environment | Difficulty | Title |",
            "|---|---|---|---|---:|---|",
        ]
        for task in sorted(by_qcat[qcat], key=lambda t: str(t.get("task_id", ""))):
            lines.append(
                f"| `{_escape(task.get('task_id'))}` "
                f"| `{_escape(task.get('role'))}` "
                f"| {_escape(task.get('benchmark_split'))} "
                f"| [`{_escape(task.get('environment_id'))}`]"
                f"(environment-catalog.md#{_escape(task.get('environment_id'))}) "
                f"| {_escape(task.get('difficulty_tier', task.get('difficulty')))} "
                f"| {_escape(task.get('title'))} |"
            )

    lines += [
        "",
        "## Adding a task",
        "",
        (
            "The corpus is versioned JSON — see "
            "[Adding a task](../guides/adding-a-task.md) for the schema, the fidelity gate a "
            "new task must pass, and the review checklist. New tasks are genuinely welcome; "
            "corpus breadth is the main thing limiting what AOBench can measure."
        ),
        "",
    ]
    return "\n".join(lines)


def render_env_catalog(envs: list[dict[str, Any]], tasks: list[dict[str, Any]]) -> str:
    tasks_per_env = Counter(str(t.get("environment_id", "")) for t in tasks)
    grounded = [e for e in envs if str(e["environment_id"]).startswith("env_m100_")]

    lines = [
        "---",
        'title: "AOBench environment catalog — every HPC snapshot bundle"',
        (
            'description: "The complete catalog of AOBench\'s '
            f'{len(envs)} deterministic HPC environment snapshot bundles, including the '
            f'{len(grounded)} built from real CINECA Marconi100 ExaData."'
        ),
        "---",
        "",
        GENERATED_NOTE,
        "",
        "# Environment catalog",
        "",
        (
            f"AOBench ships **{len(envs)} deterministic environment snapshot bundles**: "
            f"**{len(envs) - len(grounded)} synthetic** and **{len(grounded)} built from real "
            "operational data** from CINECA's 980-node Marconi100 Tier-0 supercomputer, via the "
            "public [M100 ExaData release](../guides/m100_environments.md)."
        ),
        "",
        (
            "A bundle is a directory of frozen files — SLURM state, telemetry time series, "
            "documentation, RBAC policy, incident metadata — that the mock tools read from. "
            "Nothing in a run touches a live system, which is what makes a result reproducible "
            "on someone else's laptop years later."
        ),
        "",
        "Reproduce this page from your own checkout:",
        "",
        "```bash",
        "aobench list envs --json",
        "```",
        "",
        "## All bundles",
        "",
        "| Environment | Grounding | Cluster | Scenario | Tasks | Sources | Snapshot |",
        "|---|---|---|---|---:|---|---|",
    ]
    for env in envs:
        env_id = str(env["environment_id"])
        grounding = "**real M100**" if env_id.startswith("env_m100_") else "synthetic"
        lines.append(
            f"| <a id=\"{env_id}\"></a>`{env_id}` "
            f"| {grounding} "
            f"| {_escape(env.get('cluster_name'))} "
            f"| {_escape(env.get('scenario_type'))} "
            f"| {tasks_per_env.get(env_id, 0)} "
            f"| {_escape(', '.join(env.get('included_sources') or []))} "
            f"| {_escape(env.get('snapshot_name'))} |"
        )

    lines += [
        "",
        "## Grounded environments in detail",
        "",
        (
            "These six bundles replay real Marconi100 telemetry and Slurm records. The "
            "scenarios below actually happened on the machine."
        ),
        "",
    ]
    for env in grounded:
        env_id = str(env["environment_id"])
        lines += [
            f"### `{env_id}` — {_escape(env.get('snapshot_name'))}",
            "",
            f"- **Scenario type:** `{_escape(env.get('scenario_type'))}`",
            f"- **Snapshot timestamp:** {_escape(env.get('snapshot_timestamp'))}",
            f"- **Roles supported:** {', '.join(f'`{r}`' for r in env.get('supported_roles') or [])}",
            f"- **Categories:** {', '.join(f'`{c}`' for c in env.get('supported_categories') or [])}",
            f"- **Tasks targeting it:** {tasks_per_env.get(env_id, 0)}",
            "",
            _escape(env.get("description")) or "_No description recorded._",
            "",
        ]

    lines += [
        "## Adding an environment",
        "",
        (
            "See [Adding an environment](../guides/adding-an-environment.md) for the bundle "
            "layout, the manifest format, and the fidelity checks a new snapshot must pass. "
            "Bundles grounded in real facility data are especially valuable — if you operate a "
            "cluster and can publish a sanitised snapshot, please "
            "[open a discussion](https://github.com/MSKazemi/aobench/discussions)."
        ),
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if pages are out of date")
    args = parser.parse_args()

    tasks = _load_tasks()
    envs = _load_envs()
    outputs = {
        TASK_PAGE: render_task_catalog(tasks),
        ENV_PAGE: render_env_catalog(envs, tasks),
    }

    stale = []
    for path, content in outputs.items():
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(path)

    if args.check:
        if stale:
            print("Catalog pages are out of date:", file=sys.stderr)
            for path in stale:
                print(f"  - {path.relative_to(ROOT)}", file=sys.stderr)
            print("\nRun `make catalog` and commit the result.", file=sys.stderr)
            return 1
        print(f"catalog OK — {len(tasks)} tasks, {len(envs)} environments")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
